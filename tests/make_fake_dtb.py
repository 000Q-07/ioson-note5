#!/usr/bin/env python3
"""Build SYNTHETIC flattened device trees for tests/test_discover.c.

These are not Note 5 data. The values are invented (they merely have the shape
of an Exynos phone's tree) so the parser can be checked against answers known
in advance. Writes full.dtb, minimal.dtb, cells1.dtb and expected.h (the
single source of truth for the expected values) into the output directory.

Usage: make_fake_dtb.py OUTDIR
"""
import os
import struct
import sys


class Dtb:
    def __init__(self):
        self.st = bytearray()
        self.strings = bytearray()
        self.off = {}

    def _pad(self):
        while len(self.st) % 4:
            self.st += b'\0'

    def _name(self, n):
        if n not in self.off:
            self.off[n] = len(self.strings)
            self.strings += n.encode() + b'\0'
        return self.off[n]

    def begin(self, name):
        self.st += struct.pack('>I', 1) + name.encode() + b'\0'
        self._pad()

    def end(self):
        self.st += struct.pack('>I', 2)

    def nop(self):
        self.st += struct.pack('>I', 4)

    def prop(self, name, data=b''):
        self.st += struct.pack('>III', 3, len(data), self._name(name)) + data
        self._pad()

    def u32(self, name, *vals):
        self.prop(name, b''.join(struct.pack('>I', v) for v in vals))

    def s(self, name, text):
        self.prop(name, text.encode() + b'\0')

    def build(self):
        body = bytes(self.st) + struct.pack('>I', 9)
        off_rsv, rsv = 0x28, b'\0' * 16
        off_st = off_rsv + len(rsv)
        off_str = off_st + len(body)
        while (off_str + len(self.strings)) % 4:       # keep the blob 4-byte sized
            self.strings += b'\0'
        total = off_str + len(self.strings)
        hdr = struct.pack('>10I', 0xd00dfeed, total, off_st, off_str, off_rsv,
                          17, 16, 0, len(self.strings), len(body))
        return hdr + rsv + body + bytes(self.strings)


def c64(v):
    return struct.pack('>Q', v)


# --- invented values (also written to expected.h) ---
RAM0 = (0x80000000, 0x40000000)
RAM1 = (0xc0000000, 0x20000000)
RAMOOPS = (0x92100000, 0x100000)
REC, CON, FTR, PMSG = 0x1000, 0x40000, 0, 0x20000
FBRESV = (0xcc000000, 0x1000000)
FBARG = 0xcc000000
CPUS = [0x0, 0x1, 0x2, 0x3, 0x100, 0x101, 0x102, 0x103]
INITRD = (0x84000000, 0x84800000)
BOOTARGS = 'console=ram androidboot.x=1 s3cfb.bootloaderfb=0xcc000000 quiet'


def full():
    d = Dtb()
    d.begin('')
    d.u32('#address-cells', 2)
    d.u32('#size-cells', 2)
    d.begin('chosen')
    d.s('bootargs', BOOTARGS)
    d.nop()
    d.prop('linux,initrd-start', c64(INITRD[0]))
    d.prop('linux,initrd-end', c64(INITRD[1]))
    d.end()
    d.begin('memory@80000000')
    d.s('device_type', 'memory')
    d.prop('reg', c64(RAM0[0]) + c64(RAM0[1]) + c64(RAM1[0]) + c64(RAM1[1]))
    d.end()
    d.begin('memory-controller@10000000')      # must NOT be taken as RAM
    d.prop('reg', c64(0x10000000) + c64(0x1000))
    d.end()
    d.begin('reserved-memory')
    d.u32('#address-cells', 2)
    d.u32('#size-cells', 2)
    d.prop('ranges')
    d.begin('ramoops@92100000')
    d.prop('reg', c64(RAMOOPS[0]) + c64(RAMOOPS[1]))
    d.u32('record-size', REC)
    d.u32('console-size', CON)
    d.u32('ftrace-size', FTR)
    d.u32('pmsg-size', PMSG)
    d.end()
    d.begin('framebuffer@cc000000')
    d.prop('reg', c64(FBRESV[0]) + c64(FBRESV[1]))
    d.end()
    d.end()
    d.begin('cpus')
    d.u32('#address-cells', 1)
    d.u32('#size-cells', 0)
    for c in CPUS:
        d.begin('cpu@%x' % c)
        d.u32('reg', c)
        d.end()
    d.end()
    d.end()
    return d.build()


def minimal():
    d = Dtb()
    d.begin('')
    d.end()
    return d.build()


def cells1():
    d = Dtb()
    d.begin('')
    d.u32('#address-cells', 1)
    d.u32('#size-cells', 1)
    d.begin('memory')
    d.u32('reg', 0x80000000, 0x40000000)
    d.end()
    d.end()
    return d.build()


def expected():
    pre = RAMOOPS[1] - CON - FTR - PMSG          # dump area
    cnt = pre // REC
    used = cnt * (pre // cnt)
    con = RAMOOPS[0] + used
    lines = [
        '/* generated by make_fake_dtb.py */',
        f'#define E_RAM0_BASE {RAM0[0]:#x}ULL', f'#define E_RAM0_SIZE {RAM0[1]:#x}ULL',
        f'#define E_RAM1_BASE {RAM1[0]:#x}ULL', f'#define E_RAM1_SIZE {RAM1[1]:#x}ULL',
        f'#define E_RAMOOPS_BASE {RAMOOPS[0]:#x}ULL', f'#define E_RAMOOPS_SIZE {RAMOOPS[1]:#x}ULL',
        f'#define E_REC {REC}', f'#define E_CON {CON:#x}', f'#define E_FTR {FTR}', f'#define E_PMSG {PMSG:#x}',
        f'#define E_ZONE_CONSOLE {con:#x}ULL', f'#define E_ZONE_FTRACE {con + CON:#x}ULL',
        f'#define E_ZONE_PMSG {con + CON + FTR:#x}ULL',
        f'#define E_FBRESV_BASE {FBRESV[0]:#x}ULL', f'#define E_FBRESV_SIZE {FBRESV[1]:#x}ULL',
        f'#define E_FBARG {FBARG:#x}ULL',
        f'#define E_NCPU {len(CPUS)}',
        '#define E_CPUS { ' + ', '.join(f'{c:#x}ULL' for c in CPUS) + ' }',
        f'#define E_INITRD_START {INITRD[0]:#x}ULL', f'#define E_INITRD_END {INITRD[1]:#x}ULL',
        f'#define E_BOOTARGS "{BOOTARGS}"',
    ]
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    for name, blob in (('full', full()), ('minimal', minimal()), ('cells1', cells1())):
        with open(os.path.join(out, name + '.dtb'), 'wb') as f:
            f.write(blob)
    with open(os.path.join(out, 'expected.h'), 'w') as f:
        f.write(expected())
    print('wrote', out)
